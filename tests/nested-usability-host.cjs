const assert = require('node:assert/strict');
const vscode = require('vscode');
const { resolve } = require('node:path');
const { waitFor } = require('./runtime-fixture.cjs');

async function checkUsability(frame) {
  await frame.getByRole('button', { name: 'Vertical', exact: true }).click();
  const graph = frame.locator('.nested-scroll');
  await waitFor(async () => await graph.evaluate((node) => node.scrollHeight > node.clientHeight));
  await graph.evaluate((node) => { node.scrollTop = 0; document.scrollingElement.scrollTop = 0; });
  await graph.hover({ position: { x: 30, y: 40 } });
  const top = await frame.evaluate(() => document.scrollingElement.scrollTop);
  await frame.page().mouse.wheel(0, 100);
  await waitFor(async () => await graph.evaluate((node) => node.scrollTop > 0));
  assert.equal(await frame.evaluate(() => document.scrollingElement.scrollTop), top, 'graph consumes scrolling while it has room');
  await graph.evaluate((node) => { node.scrollTop = node.scrollHeight; });
  await frame.page().mouse.wheel(0, 400);
  await waitFor(async () => await frame.evaluate(() => document.scrollingElement.scrollTop) > top);
  const scrolled = await frame.evaluate(() => document.scrollingElement.scrollTop);
  await graph.evaluate((node) => { node.scrollTop = 0; });
  await graph.hover({ position: { x: 30, y: 40 } });
  await frame.page().mouse.wheel(0, -400);
  await waitFor(async () => await frame.evaluate(() => document.scrollingElement.scrollTop) < scrolled);
  const header = await frame.locator('.step-detail-header').boundingBox();
  assert.ok(header.height < 180, `compact step header: ${header.height}px`);
  await frame.locator('.step-inspector').scrollIntoViewIfNeeded();
  await frame.page().screenshot({ path: resolve(__dirname, '../.vscode-test/compact-step-details.png') });

  await frame.getByRole('button', { name: 'Close step details', exact: true }).click();
  await frame.locator('.step-inspector').waitFor({ state: 'detached' });
  await vscode.commands.executeCommand('maestrun.refresh');
  assert.equal(await frame.locator('.step-inspector').count(), 0);
  await frame.locator('.nested-task[data-task-id=build] .flow-node[data-step-id=testing]').click();
  await frame.locator('.step-inspector #detail-title').filter({ hasText: 'Tests' }).waitFor();
  await frame.getByRole('button', { name: 'Close step details', exact: true }).click();
  await frame.locator('.step-inspector').waitFor({ state: 'detached' });
  await frame.locator('.nested-task[data-task-id=build] .nested-task-title').click();
  await frame.locator('.step-inspector #detail-title').filter({ hasText: 'Build' }).waitFor();
  await frame.getByRole('button', { name: 'Close step details', exact: true }).click();
  await frame.locator('.step-inspector').waitFor({ state: 'detached' });
  await frame.getByRole('button', { name: 'Detailed tasks', exact: true }).click();
  const visibleIds = () => frame.locator('.task-row:visible').evaluateAll((rows) => rows.map((row) => row.dataset.taskId));
  await waitFor(async () => (await visibleIds()).length === 5);
  assert.deepEqual(await visibleIds(), ['__orchestrator__', 'build', 'check', 'review', 'generated']);
  const toggle = frame.locator('.task-tree-toggle[data-task-id=build]');
  await toggle.focus();
  await toggle.press('Enter');
  assert.deepEqual(await visibleIds(), ['__orchestrator__', 'build']);
  await frame.locator('#task-filter').fill('Generated check');
  assert.deepEqual(await visibleIds(), ['__orchestrator__', 'build', 'generated']);
  await frame.locator('#task-filter').fill('');
  assert.deepEqual(await visibleIds(), ['__orchestrator__', 'build']);
  await vscode.commands.executeCommand('maestrun.refresh');
  await waitFor(async () => await toggle.getAttribute('aria-expanded') === 'false');
  await toggle.click();
  await frame.locator('#task-sort').selectOption('title');
  assert.deepEqual(await visibleIds(), ['__orchestrator__', 'build', 'check', 'review', 'generated']);
  await frame.locator('#task-sort').selectOption('status');
  assert.deepEqual(await visibleIds(), ['__orchestrator__', 'build', 'check', 'review', 'generated']);
  await frame.locator('.task-select[data-task-id=generated]').click();
  await waitFor(async () => await frame.locator('.dashboard').getAttribute('data-selection') === 'generated');
  await frame.page().screenshot({ path: resolve(__dirname, '../.vscode-test/task-directory-tree.png') });
}
module.exports = { checkUsability };
